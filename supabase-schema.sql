-- Jalankan SQL ini di Supabase Dashboard -> SQL Editor -> New Query
CREATE TABLE IF NOT EXISTS public.comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author TEXT NOT NULL CHECK (char_length(trim(author)) > 0 AND char_length(author) <= 80),
  text TEXT NOT NULL CHECK (char_length(trim(text)) > 0 AND char_length(text) <= 1000),
  avatar_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;

-- Izinkan semua pengunjung membaca komentar
CREATE POLICY "Allow public read comments"
  ON public.comments
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- Izinkan semua pengunjung mengirim komentar baru
CREATE POLICY "Allow public insert comments"
  ON public.comments
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);
